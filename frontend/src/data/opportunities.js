export function filterAndSortOpportunities(listings, query, filters, sort) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean)

  return listings.filter((opportunity) => {
    const searchable = [
      opportunity.title,
      opportunity.organization,
      opportunity.description,
      opportunity.location,
      opportunity.category,
      opportunity.opportunityType,
      opportunity.eligibility,
      opportunity.funding,
      opportunity.benefit
    ].join(' ').toLocaleLowerCase()

    return terms.every((term) => searchable.includes(term)) &&
      opportunityFilterFields.every(({ key }) => {
        if (!filters[key]) return true
        if (key === 'location' && filters[key] === 'other-africa') {
          return opportunity.region === 'Africa' && !primaryLocations.includes(opportunity.location)
        }
        return opportunity[key] === filters[key]
      })
  }).sort((a, b) => {
    if (sort === 'deadline') return a.deadline.localeCompare(b.deadline)
    if (sort === 'title') return a.title.localeCompare(b.title)
    return b.listedDate.localeCompare(a.listedDate)
  })
}
