export function filterAndSortJobs(listings, query, filters, sort) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean)
  return listings.filter((job) => {
    const searchable = [job.title, job.organization, job.description, job.location, job.jobType, job.workType, ...job.requirements].join(' ').toLocaleLowerCase()
    return terms.every((term) => searchable.includes(term)) &&
      jobFilterFields.every(({ key }) => {
        if (!filters[key]) return true
        if (key === 'location' && filters[key] === 'other-africa') {
          return job.region === 'Africa' && !primaryLocations.includes(job.location)
        }
        return job[key] === filters[key]
      })
  }).sort((a, b) => {
    if (sort === 'deadline') return a.deadline.localeCompare(b.deadline)
    if (sort === 'title') return a.title.localeCompare(b.title)
    return b.listedDate.localeCompare(a.listedDate)
  })
}
